// Reads the bundled Reel fonts and writes web/js/scenes/reel-fonts-data.js: for each font its units per em, cap height,
// x-height, stem weight guess and the ranges of characters it has (from the 'cmap' table). The scene uses these to
// size every font so capitals look equally tall, and to draw any character a font lacks in Anton instead.
// Run again only when a font file changes:  node tools/font-metrics.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = ['Anton', 'BebasNeue', 'ArchivoBlack', 'RubikMonoOne', 'PermanentMarker', 'Bangers', 'SpecialElite', 'Bungee', 'AlfaSlabOne', 'BowlbyOne'];

function tables(dv) {
  const n = dv.getUint16(4);
  const out = {};
  for (let i = 0; i < n; i++) {
    const o = 12 + i * 16;
    const tag = String.fromCharCode(dv.getUint8(o), dv.getUint8(o + 1), dv.getUint8(o + 2), dv.getUint8(o + 3));
    out[tag] = dv.getUint32(o + 8);
  }
  return out;
}

function cmapRanges(dv, base) {
  const n = dv.getUint16(base + 2);
  let best = null;
  for (let i = 0; i < n; i++) {
    const pid = dv.getUint16(base + 4 + i * 8);
    const eid = dv.getUint16(base + 6 + i * 8);
    const off = base + dv.getUint32(base + 8 + i * 8);
    const fmt = dv.getUint16(off);
    const score = (pid === 3 && eid === 10 ? 4 : 0) + (pid === 3 && eid === 1 ? 3 : 0) + (pid === 0 ? 2 : 0);
    if ((fmt === 4 || fmt === 12) && (!best || score > best.score)) best = { off, fmt, score };
  }
  const ranges = [];
  const { off, fmt } = best;
  if (fmt === 12) {
    const groups = dv.getUint32(off + 12);
    for (let g = 0; g < groups; g++) {
      const p = off + 16 + g * 12;
      ranges.push([dv.getUint32(p), dv.getUint32(p + 4)]);
    }
  } else {
    const segX2 = dv.getUint16(off + 6);
    const end = off + 14;
    const start = end + segX2 + 2;
    const delta = start + segX2;
    const rangeOff = delta + segX2;
    for (let s = 0; s < segX2 / 2; s++) {
      const e = dv.getUint16(end + s * 2);
      const b = dv.getUint16(start + s * 2);
      if (b === 0xffff) continue;
      // a segment can have holes (glyph id 0 = missing): walk it so the ranges are exact
      const ro = dv.getUint16(rangeOff + s * 2);
      let runStart = -1;
      for (let c = b; c <= e + 1; c++) {
        let has = false;
        if (c <= e) {
          if (ro === 0) has = ((c + dv.getUint16(delta + s * 2)) & 0xffff) !== 0;
          else {
            const gp = rangeOff + s * 2 + ro + (c - b) * 2;
            const gid = dv.getUint16(gp);
            has = gid !== 0;
          }
        }
        if (has && runStart < 0) runStart = c;
        if (!has && runStart >= 0) {
          ranges.push([runStart, c - 1]);
          runStart = -1;
        }
      }
    }
  }
  return ranges.sort((a, b) => a[0] - b[0]);
}

const out = {};
for (const name of FONTS) {
  const buf = readFileSync(path.join(root, 'web/fonts', `${name}.ttf`));
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  const t = tables(dv);
  const upm = dv.getUint16(t.head + 18);
  const os2 = t['OS/2'];
  const ver = dv.getUint16(os2);
  const capH = ver >= 2 ? dv.getInt16(os2 + 88) : 0;
  const xH = ver >= 2 ? dv.getInt16(os2 + 86) : 0;
  const weight = dv.getUint16(os2 + 4);
  const ranges = cmapRanges(dv, t.cmap);
  out[name] = { upm, capH: capH || Math.round(upm * 0.7), xH: xH || Math.round(upm * 0.5), weight, ranges };
  console.log(name.padEnd(16), 'upm', upm, 'cap', capH, 'x', xH, 'weight', weight, 'ranges', ranges.length);
}

const body = `// GENERATED by tools/font-metrics.mjs from the font files in web/fonts. Do not edit by hand.
// Per font: units per em, cap height, x-height (font units), the OS/2 weight class and the character ranges it has.
export const FONT_DATA = ${JSON.stringify(out)};
`;
writeFileSync(path.join(root, 'web/js/scenes/reel-fonts-data.js'), body);
console.log('wrote web/js/scenes/reel-fonts-data.js');
