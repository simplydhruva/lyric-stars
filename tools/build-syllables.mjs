// Builds web/js/data/syllable-exceptions.js from the CMU Pronouncing Dictionary.
// Only words where the vowel-group rule is wrong are stored, which keeps the file small.
//
//   curl -L -o cmudict.dict https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict
//   node tools/build-syllables.mjs path/to/cmudict.dict
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/build-syllables.mjs <cmudict.dict>');
  process.exit(1);
}

// Write an empty table first so syllables.js can be imported for the comparison.
const out = path.join(ROOT, 'web/js/data/syllable-exceptions.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
if (!fs.existsSync(out)) fs.writeFileSync(out, "export const EXCEPTIONS = '';\n");
const { vowelGroupSyllables } = await import('../web/js/syllables.js');

const counts = new Map();
for (const line of fs.readFileSync(src, 'utf8').split('\n')) {
  // "word PH1 ON0 ..." ; alternates are "word(2) ...", comments after '#'
  const m = line.replace(/#.*/, '').trim().match(/^([a-z']+)(?:\(\d+\))?\s+(.+)$/);
  if (!m) continue;
  const [, word, phones] = m;
  const n = (phones.match(/\d/g) || []).length;
  if (!n) continue;
  // Prefer the first pronunciation listed; it is the most common one.
  if (!counts.has(word)) counts.set(word, n);
}

const byCount = new Map();
let kept = 0;
for (const [word, n] of counts) {
  const letters = word.replace(/[^a-z]/g, '');
  if (!letters || vowelGroupSyllables(letters) === n) continue;
  if (!byCount.has(n)) byCount.set(n, []);
  byCount.get(n).push(word);
  kept++;
}

const body = [...byCount.entries()]
  .sort((a, b) => a[0] - b[0])
  .map(([n, words]) => `${n}:${words.sort().join(' ')}`)
  .join('|');

fs.writeFileSync(
  out,
  `// Generated by tools/build-syllables.mjs from the CMU Pronouncing Dictionary
// (Copyright (C) 1993-2015 Carnegie Mellon University, BSD-style license).
// Words whose syllable count differs from the vowel-group rule, as "count:words|...".
export const EXCEPTIONS = ${JSON.stringify(body)};
`
);
console.log(`${counts.size} words read, ${kept} exceptions written to ${path.relative(ROOT, out)} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
