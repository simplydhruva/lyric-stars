// Reads the bundled pixel fonts and writes web/js/scenes/pixel-font-data.js: for each font the ranges of characters it has
// (from the 'cmap' table) and the advance width of every printable ASCII character, in 1/1000 em. The Pixel scene uses the
// ranges to know which characters the pixel font can draw itself, and the unit tests use the widths as the "real metrics"
// to check line wrapping without a browser. Run again only when a font file changes:  node tools/pixel-font-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = { press: 'PressStart2P', silk: 'Silkscreen' };

function tables(dv) {
  const n = dv.getUint16(4);
  const out = {};
  for (let i = 0; i < n; i++) {
    const o = 12 + i * 16;
    out[String.fromCharCode(dv.getUint8(o), dv.getUint8(o + 1), dv.getUint8(o + 2), dv.getUint8(o + 3))] = dv.getUint32(o + 8);
  }
  return out;
}

// code point -> glyph id, from the best format 4 / 12 cmap subtable
function cmap(dv, base) {
  const n = dv.getUint16(base + 2);
  let best = null;
  for (let i = 0; i < n; i++) {
    const pid = dv.getUint16(base + 4 + i * 8);
    const eid = dv.getUint16(base + 6 + i * 8);
    const off = base + dv.getUint32(base + 8 + i * 8);
    const fmt = dv.getUint16(off);
    const score = (pid === 3 && eid === 10 ? 4 : 0) + (pid === 3 && eid === 1 ? 3 : 0) + (pid === 0 ? 2 : 0);
    if ((fmt === 4 || fmt === 12) && (!best || score > best.score)) best = { off, fmt, score };
  }
  const map = new Map();
  const { off, fmt } = best;
  if (fmt === 12) {
    const groups = dv.getUint32(off + 12);
    for (let g = 0; g < groups; g++) {
      const p = off + 16 + g * 12;
      const a = dv.getUint32(p);
      const b = dv.getUint32(p + 4);
      const gid = dv.getUint32(p + 8);
      for (let c = a; c <= b; c++) map.set(c, gid + c - a);
    }
  } else {
    const segX2 = dv.getUint16(off + 6);
    const end = off + 14;
    const start = end + segX2 + 2;
    const delta = start + segX2;
    const rangeOff = delta + segX2;
    for (let s = 0; s < segX2 / 2; s++) {
      const e = dv.getUint16(end + s * 2);
      const b = dv.getUint16(start + s * 2);
      if (b === 0xffff) continue;
      const ro = dv.getUint16(rangeOff + s * 2);
      for (let c = b; c <= e; c++) {
        let gid;
        if (ro === 0) gid = (c + dv.getUint16(delta + s * 2)) & 0xffff;
        else gid = dv.getUint16(rangeOff + s * 2 + ro + (c - b) * 2);
        if (gid !== 0) map.set(c, gid);
      }
    }
  }
  return map;
}

const out = {};
for (const [id, name] of Object.entries(FONTS)) {
  const buf = readFileSync(path.join(root, 'web/fonts', `${name}.ttf`));
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  const t = tables(dv);
  const upm = dv.getUint16(t.head + 18);
  const nHm = dv.getUint16(t.hhea + 34);
  const map = cmap(dv, t.cmap);
  const adv = (gid) => dv.getUint16(t.hmtx + Math.min(gid, nHm - 1) * 4);
  const cps = [...map.keys()].sort((a, b) => a - b);
  const ranges = [];
  for (const c of cps) {
    const last = ranges[ranges.length - 1];
    if (last && c === last[1] + 1) last[1] = c;
    else ranges.push([c, c]);
  }
  const widths = [];
  for (let c = 32; c < 127; c++) widths.push(map.has(c) ? Math.round((adv(map.get(c)) * 1000) / upm) : null);
  out[id] = { file: `${name}.ttf`, ranges, widths };
}
const text = `// Generated by tools/pixel-font-data.mjs from the bundled pixel fonts. Do not edit by hand.
// ranges: [first, last] code points the font has. widths: advance of ASCII 32..126 in 1/1000 em (null: not in the font).
export const PIXEL_FONT_DATA = ${JSON.stringify(out)};
`;
writeFileSync(path.join(root, 'web/js/scenes/pixel-font-data.js'), text);
for (const [id, f] of Object.entries(out)) console.log(id, f.file, 'ranges', f.ranges.length, 'chars', f.ranges.reduce((n, r) => n + r[1] - r[0] + 1, 0), 'width of A / i:', f.widths[33], f.widths[73]);
